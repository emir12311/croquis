#!/usr/bin/env node
/**
 * Generate the v0.3 inventory from what the app actually ships.
 *
 * The rewrite plan must not carry a hand-written part list: parts, presets and
 * tests are discovered here, and the gates compare against this output. The
 * generated Markdown and JSON are checked in so a diff shows a changed surface,
 * but the script is the source of truth.
 *
 *   npm run inventory
 */
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createServer } from 'vite'

const root = process.cwd()
const server = await createServer({
  root,
  configFile: false,
  appType: 'custom',
  logLevel: 'error',
  server: { middlewareMode: true },
})

function hash(text) {
  return createHash('sha256').update(text).digest('hex').slice(0, 12)
}

function testNames(path) {
  const text = readFileSync(path, 'utf8')
  const names = []
  for (const match of text.matchAll(/(?:^|\n)\s*(?:it|test)\(\s*(['"`])([\s\S]*?)\1/g)) {
    names.push(match[2].replace(/\s+/g, ' ').trim())
  }
  return names
}

function rustTests() {
  const out = []
  const dir = join(root, 'src-tauri/src')
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.rs')).sort()) {
    const text = readFileSync(join(dir, file), 'utf8')
    for (const match of text.matchAll(/#\[test\][\s\S]*?\n\s*fn\s+([A-Za-z0-9_]+)\s*\(/g)) {
      out.push({ file, name: match[1] })
    }
  }
  return out
}

let parts
let presets
try {
  parts = (await server.ssrLoadModule('/src/lib/parts.ts')).PARTS
  presets = (await server.ssrLoadModule('/src/lib/presets.ts')).PRESETS
} finally {
  await server.close()
}

const catalogue = parts.map((part) => ({
  kind: part.kind,
  label: part.label,
  tag: part.tag,
  diagramType: part.diagramType ?? null,
  attrs: part.attrs,
  live: !!part.live,
  noPins: !!part.noPins,
  fields: (part.fields ?? []).map((field) => ({
    name: field.name,
    label: field.label,
    control: field.control.kind,
    ...(field.control.kind === 'select'
      ? { options: field.control.options.map((option) => option.value) }
      : {}),
    ...(field.control.kind === 'range'
      ? {
          min: field.control.min,
          max: field.control.max,
          step: field.control.step,
        }
      : {}),
  })),
}))

const presetList = presets.map((preset) => {
  const doc = JSON.parse(preset.text)
  return {
    id: preset.id,
    label: preset.label,
    group: preset.group,
    parts: doc.parts.map((part) => part.type),
    connections: doc.connections.length,
    sketchHash: hash(doc.sketch),
  }
})

const frontendTests = readdirSync(join(root, 'src/lib'))
  .filter((file) => file.endsWith('.test.ts'))
  .sort()
  .map((file) => ({
    file,
    tests: testNames(join(root, 'src/lib', file)),
  }))

const inventory = {
  version: JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version,
  parts: catalogue,
  presets: presetList,
  tests: {
    frontend: frontendTests,
    rust: rustTests(),
  },
}

writeFileSync(
  join(root, 'docs/v0.3-baseline.json'),
  `${JSON.stringify(inventory, null, 2)}\n`,
)

const groupRows = Object.entries(
  presetList.reduce((groups, preset) => {
    ;(groups[preset.group] ??= []).push(preset.label)
    return groups
  }, {}),
)
  .map(([group, labels]) => `| ${group} | ${labels.join(', ')} |`)
  .join('\n')

const partRows = catalogue
  .map(
    (part) =>
      `| \`${part.kind}\` | ${part.label} | \`${part.tag}\` | ${
        part.fields.map((field) => field.name).join(', ') || '—'
      } |`,
  )
  .join('\n')

const frontendRows = frontendTests
  .map((file) => `| \`${file.file}\` | ${file.tests.length} |`)
  .join('\n')

const rustRows = inventory.tests.rust
  .map((test) => `| \`${test.file}\` | \`${test.name}\` |`)
  .join('\n')

writeFileSync(
  join(root, 'docs/v0.3-baseline.md'),
  `# v0.3 inventory baseline

> Generated by \`tools/inventory.mjs\`. Do not edit by hand; run \`npm run inventory\`.

This is the measured surface the egui rewrite must preserve. The numbers below
come from the source at generation time, not from a list in the plan.

## Parts

| Kind | Label | Element tag | Editable fields |
| --- | --- | --- | --- |
${partRows}

## Presets

| Group | Circuits |
| --- | --- |
${groupRows}

| Id | Label | Parts | Connections | Sketch hash |
| --- | --- | --- | --- | --- |
${presetList
  .map(
    (preset) =>
      `| \`${preset.id}\` | ${preset.label} | ${preset.parts.length} | ${preset.connections} | \`${preset.sketchHash}\` |`,
  )
  .join('\n')}

## Tests

> The frontend counts are explicit \`it()\`/\`test()\` declarations. Cases generated
> by loops are executed by Vitest but are not expanded here; \`npm test\` reports
> the executed total.

### Frontend test declarations

| File | Tests |
| --- | --- |
${frontendRows}

### Rust

| File | Test |
| --- | --- |
${rustRows}

## How to use this

- Compare a new implementation against the preset corpus and the test list above.
- A new generated diff means the old app's surface changed; update the parity
  plan rather than silently accepting a stale baseline.
- Measurements (startup, memory, package size) are not in this baseline yet;
  Phase 0.1 adds them with the same generated-document approach.
`,
)

console.log(
  `inventory: ${catalogue.length} parts, ${presetList.length} presets, ` +
    `${frontendTests.reduce((n, file) => n + file.tests.length, 0)} frontend test declarations, ` +
    `${inventory.tests.rust.length} Rust tests`,
)

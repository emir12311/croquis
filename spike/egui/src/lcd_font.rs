/// The five-by-eight dots of a character code, or nothing for a code the table
/// does not cover (the real display would show its own odd glyphs there).
pub fn glyph(code: u8) -> Option<&'static [u8; 8]> {
    if !(FIRST..=LAST).contains(&code) {
        return None;
    }
    Some(&GLYPHS[usize::from(code - FIRST)])
}
